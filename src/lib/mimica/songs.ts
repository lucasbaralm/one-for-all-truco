// de tudo: muita MPB e rock nacional, pagode, axé, sertanejo clássico e atual, os hits dos anos 80, 90 e 2000, e os de hoje.
// Como foi montada (curadoria + dados, em 03/11/2026):
//  • cada lado foi montado por década (distribuição final — Brasil: 80s 30 · 90s 62 · 2000s 83 · 2010s 70 · 2020s 55; mundo: 80s 25 ·
//    90s 60 · 2000s 80 · 2010s 80 · 2020s 55), escolhendo
//    músicas que todo mundo reconhece e usando o total de streams do Spotify (kworb.net/spotify/songs.html no mundo;
//    kworb.net/spotify/country/br_daily_totals.html no Brasil) pra conferir título/artista e desempatar. O que o Spotify
//    não mostra (muita coisa dos anos 80 e 90, quase toda a MPB) entrou pela curadoria;
//  • no máximo 6 músicas por artista no Brasil e 5 no mundo (senão três artistas ocupam a mesa);
//  • nada de antes de 1984, nenhuma música nas duas listas, nenhum título repetido, nenhum medley, set de DJ ou palavrão no título;
