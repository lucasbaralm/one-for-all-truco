/** "avião" → "AVIAO": maiúsculas, sem acento, só A–Z (o resto é descartado). */
export function normalize(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toUpperCase()
    .replace(/[^A-Z]/g, "");
}
